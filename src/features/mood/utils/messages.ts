/** เลือกข้อความจากรายการด้วยเลขใด ๆ (เลขสุ่มหรือเลขเดือน) ให้เทสต์ได้ */
export function pickMessage(list: readonly string[], n: number): string {
  if (list.length === 0) return ''
  return list[Math.abs(Math.floor(n)) % list.length]
}

